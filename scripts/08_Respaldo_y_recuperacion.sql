
--RESPALDO Y RECUPERACION

USE master;
ALTER DATABASE BusRD SET RECOVERY FULL;
GO

ALTER DATABASE BusRD SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
GO

--BACKUP FULL
BACKUP DATABASE BusRD
TO DISK = 'C:\Respaldosdb\BusRD_Full.bak'
WITH INIT, FORMAT,
NAME = 'Respaldo completo de BusRD';

--BACKUP DIERENCIAL
BACKUP DATABASE BusRD 
TO DISK = 'C:\Respaldosdb\BusRD_Diff.bak'
WITH DIFFERENTIAL,
NAME = 'Respaldo diferencial de BusRD';

--BACKUP LOG
BACKUP LOG BusRD
TO DISK = 'C:\Respaldosdb\BusRD_Log.trn'
WITH NAME = 'Respaldo de log de transacciones';

--RECUPERACION CON STOPAT

BACKUP LOG BusRD 
TO DISK = 'C:\Respaldosdb\BusRD_TailLog.trn' 
WITH NO_TRUNCATE;								--En caso de que de error al backup con (WITH NORECOVERY) porque hay transacciones en el log que no estan guardadas ejecutar esto.


--Restaurar el backup completo
RESTORE DATABASE BusRD
FROM DISK = 'C:\Respaldosdb\BusRD_Full.bak'
WITH NORECOVERY;
GO

--RESTAURAR HASTA UN MOMENTO EN ESPECIFICO
RESTORE LOG BusRD
FROM DISK='C:\Respaldosdb\BusRD_Log.trn'
WITH RECOVERY, STOPAT = '2026-10-25 15:50:00';
GO

--SI LA DB SE QUEDO EN RECUPERACION
RESTORE DATABASE BusRD WITH RECOVERY;
GO

--DEVOLVEMOS LA DB A MULTIUSUARIOS
ALTER DATABASE BusRD SET MULTI_USER;
GO


